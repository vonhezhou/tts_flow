import 'package:tts_flow_dart/src/core/audio_spec.dart';
import 'package:tts_flow_dart/src/core/tts_output.dart';
import 'package:tts_flow_dart/src/core/tts_voice.dart';

enum TtsRequestState { queued, running, completed, failed, stopped, canceled }

class TtsOptions {
  const TtsOptions({this.speed, this.pitch, this.volume, this.sampleRateHz});

  final double? speed;
  final double? pitch;
  final double? volume;
  final int? sampleRateHz;

  TtsOptions copyWith({
    double? speed,
    double? pitch,
    double? volume,
    int? sampleRateHz,
  }) {
    return TtsOptions(
      speed: speed ?? this.speed,
      pitch: pitch ?? this.pitch,
      volume: volume ?? this.volume,
      sampleRateHz: sampleRateHz ?? this.sampleRateHz,
    );
  }
}

class TtsRequest {
  const TtsRequest({
    required this.requestKey,
    String? utteranceId,
    required this.text,
    this.voice,
    this.preferredFormat,
    this.options,
    this.params = const {},
    this.output,
  }) : utteranceId = utteranceId ?? requestKey;

  /// Opaque key generated by [TtsFlow] for one concrete request instance.
  ///
  /// Outputs, engines, chunks, and playback routing use this key. It is never
  /// derived from the application-facing [utteranceId].
  final String requestKey;

  /// Application-supplied correlation label, analogous to Android's
  /// `utteranceId`. It is deliberately not required to be unique.
  final String utteranceId;
  final String text;
  final TtsVoice? voice;
  final TtsAudioFormat? preferredFormat;
  final TtsOptions? options;
  final Map<String, Object> params;
  final TtsOutput? output;
}
